#!/usr/bin/env python3
# Docs: docs/02 - Tech/Downloaded Docs Process.md
"""Purpose: regenerates the Code Map from each file's Docs and Purpose comments, and each note's Related section.

Run before check_docs.py. Related and the `related` frontmatter come from the links in a note's text, in both
directions, so the vault stays two-way without hand work. The version comes from VERSION for notes passed by name.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
DOWNLOADED = "00 - Downloaded Docs"
WIKILINK = re.compile(r"\[\[([^\]|#]+)")
SOURCE_DIRS = ("src", "providers", "hosts", "tools", "crates", "tests", "packaging", "server")
SOURCE_SUFFIXES = {".ts", ".py", ".sh", ".mjs", ".rs", ".js", ""}
EXTRA = ["web/styles.css", "web/index.html", "vite.config.ts", "prototypes/ui-preview/template.html"]
SKIP = {"ID", "test.webm", "Cargo.toml", "manifest.json", "rules.json"}


def source_files():
    for folder in SOURCE_DIRS:
        for f in sorted((ROOT / folder).rglob("*")):
            if f.is_file() and f.suffix in SOURCE_SUFFIXES and f.name not in SKIP and "node_modules" not in f.parts:
                yield f
    for name in EXTRA:
        yield ROOT / name


def describe(f):
    text = f.read_text(encoding="utf-8", errors="replace")[:1500]
    doc = re.search(r"Docs: docs/(.+?)\.md", text)
    purpose = re.search(r"Purpose: (.+?)(?:\n|\*/|-->|$)", text)
    fallback = re.search(r'^"""(.+?)$', text, re.M)
    what = purpose.group(1) if purpose else fallback.group(1) if fallback else ""
    return (doc.group(1) if doc else None), what.strip().rstrip(".")


def write_code_map():
    rows = []
    for f in source_files():
        rel = f.relative_to(ROOT).as_posix()
        doc, what = describe(f)
        link = f"[[{doc}|{doc.split('/')[-1]}]]" if doc else ""
        rows.append(f"| [{rel}](../../{rel.replace(' ', '%20')}) | {what} | {link} |")
    path = DOCS / "04 - Architecture" / "Code Map.md"
    body = ("# Code Map\n\nEvery source file, generated by [update_docs_links.py](../../tools/update_docs_links.py) from the comment at the "
            "top of each file. Don't edit this table by hand.\n\n| File | Purpose | Note |\n|---|---|---|\n" + "\n".join(rows) +
            f"\n\nAlso: [VERSION](../../VERSION), [CLAUDE.md](../../CLAUDE.md). `reference/netflix-lab/` is the owner's earlier lab, kept for reference: "
            f"[[{DOWNLOADED}/Netflix Lab/README|Netflix Lab]]. The structure is in [[04 - Architecture/Overview|Overview]].\n")
    old = path.read_text(encoding="utf-8")
    front = re.match(r"---\n.*?\n---\n\n", old, re.S).group(0)
    path.write_text(front + body, encoding="utf-8")


def split(text):
    m = re.match(r"---\n(.*?)\n---\n\n?", text, re.S)
    body = text[m.end():]
    return m.group(1), body.split("\n## Related\n")[0].rstrip() + "\n"


def main(touched):
    write_code_map()
    version = (ROOT / "VERSION").read_text().split("+")[0].strip()
    notes = {p.relative_to(DOCS).with_suffix("").as_posix(): p for p in DOCS.rglob("*.md") if not p.relative_to(DOCS).as_posix().startswith(DOWNLOADED)}
    parts = {n: split(p.read_text(encoding="utf-8")) for n, p in notes.items()}
    links = {n: {t for t in WIKILINK.findall(b) if t in notes and t != n} for n, (_, b) in parts.items()}
    for n in list(links):
        for t in list(links[n]):
            links[t].add(n)
    for n, p in notes.items():
        front, body = parts[n]
        if n == "Home":
            continue
        rel = ["Home"] + sorted(links[n] - {"Home"})
        front = re.sub(r"^related: .*$", "related: [" + ", ".join(f'"[[{r}]]"' for r in rel) + "]", front, flags=re.M)
        if n in touched:
            front = re.sub(r"^version: .*$", f"version: {version}", front, flags=re.M)
        related = "\n## Related\n\n" + "\n".join(f"- [[{r}|{r.split('/')[-1]}]]" for r in rel) + "\n"
        p.write_text(f"---\n{front}\n---\n\n{body}{related}", encoding="utf-8")
    print(f"{len(notes)} notes linked")


if __name__ == "__main__":
    main(set(sys.argv[1:]))
