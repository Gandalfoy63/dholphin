// Docs: docs/02 - Tech/Testing.md
// Purpose: drives the app against the real TMDB and OMDb, using the keys in .env. Run tools/serve.mjs first.
import assert from 'node:assert/strict';
import { join } from 'node:path';
import { chromium } from 'playwright';

const URL_ = process.env.APP ?? 'http://dholphin.test:8765/', OUT = process.env.OUT ?? '/tmp';
const b = await chromium.launch({ args: ['--host-resolver-rules=MAP dholphin.test 127.0.0.1'] });
const p = await (await b.newContext({ viewport: { width: 1920, height: 1080 }, locale: 'en-GB' })).newPage();
const errors = [], bad = new Set(), hosts = new Set();
p.on('pageerror', (e) => errors.push(e.message));
p.on('response', (r) => {
  const u = new URL(r.url());
  hosts.add(u.host);
  if (r.status() >= 400) bad.add(`${r.status()} ${u.host}${u.pathname}`);
});
const until = (fn, arg) => p.waitForFunction(fn, arg, { timeout: 40000 });
const ok = (n) => console.log(`  ok  ${n}`);
const shot = (n) => p.screenshot({ path: join(OUT, `${n}.png`) });
await p.goto(URL_);
await until(() => document.activeElement?.id === 'nx');
await p.keyboard.press('Enter');
await until(() => document.querySelector('.nm'));
ok('With keys configured, setup skips asking for them');
await p.keyboard.press('Enter');
await p.click('#nx');
await until(() => document.querySelector('.prov'));
await p.click('#nx');
await until(() => document.querySelectorAll('.tc[data-t]').length === 18);
await until(() => [...document.querySelectorAll('.tc img')].filter((i) => i.complete && i.naturalWidth).length > 10);
await p.waitForTimeout(600);
await shot('real-taste');
console.log('      taste:', (await p.locator('.tc .ct').allTextContents()).slice(0, 6).join(', '));
ok('The taste grid shows real titles and real images');
for (const i of [0, 3, 7]) await p.locator('.tc[data-t]').nth(i).click();
await p.click('#nx');
await until(() => document.querySelector('[data-g="language"]'));
await p.click('#nx');
await until(() => document.querySelector('.hero .hp'));
await until(() => document.querySelectorAll('.row:not([hidden]) .card').length > 30);
await p.waitForTimeout(2500);
await shot('real-home');
const rows = await p.locator('.row:not([hidden])').evaluateAll((l) => l.map((r) => `${r.querySelector('h2').textContent} (${r.querySelectorAll('.card').length})`));
console.log('      rows:', rows.join(' | '));
for (const h of ['New Arrivals', 'Trending Now', 'Upcoming', 'Netflix']) assert.ok(rows.some((r) => r.startsWith(h)), h);
ok('Home fills from real data');
// Deep down: bands of many kinds, real award winners from Wikidata, and the feed keeps going.
for (let i = 0; i < 14; i++) {
  await p.evaluate(() => {
    const rows = [...document.querySelectorAll('.row:not([hidden])')];
    rows.at(-1)?.scrollIntoView();
    rows.at(-1)?.querySelector('.card')?.focus();
  });
  await p.waitForTimeout(1200);
}
await shot('real-deep');
const deep = await p.locator('.row.sep:not([hidden])').evaluateAll((l) => l.map((r) => `${r.dataset.row.split('-').slice(0, -2).join('-')}: ${r.querySelector('h2').textContent} (${r.querySelectorAll('.card').length}) ${[...r.querySelectorAll('.card')].slice(0, 3).map((c) => c.getAttribute('aria-label')).join(', ')}`));
console.log('      bands:\n        ' + deep.join('\n        '));
const made = await p.locator('.row').count();
console.log('      rows made:', made);
assert.ok(deep.some((d) => d.startsWith('award-')), 'an award band');
assert.ok(deep.some((d) => d.startsWith('theme-')), 'a theme band');
assert.ok(made > 30, 'more batches');
ok('Bands vary, award winners come from Wikidata, and the feed keeps going');
await p.evaluate(() => document.querySelector('.row .card')?.focus());
const broken = await p.locator('img').evaluateAll((l) => l.filter((i) => i.complete && !i.naturalWidth && i.getAttribute('loading') !== 'lazy').map((i) => i.src).slice(0, 5));
assert.deepEqual(broken, []);
await p.keyboard.press('ArrowDown');
await until(() => document.activeElement?.classList.contains('card'));
await until(() => !!document.querySelector('.card:focus .ov .tom')).catch(() => undefined);
await p.waitForTimeout(1500);
await shot('real-card');
const ov = await p.locator('.card:focus .ov').innerText();
console.log('      card:', (await p.locator('.card:focus').getAttribute('aria-label')), '|', ov.replace(/\s+/g, ' '));
assert.match(ov, /\d[.,]\d/);
ok('A focused card shows a real score');
await p.keyboard.press('Enter');
await until(() => document.querySelector('.dlayer .btns .f'));
await p.waitForTimeout(1500);
await shot('real-details');
const details = await p.locator('.dtext').innerText();
console.log('      details:', details.replace(/\s+/g, ' ').slice(0, 260));
assert.ok(details.length > 80);
ok('The details view fills from TMDB and OMDb');
await p.keyboard.press('Escape');
await until(() => !document.querySelector('.dlayer'));
await p.evaluate(() => document.querySelector('[data-go="categories"]').click());
await until(() => document.querySelectorAll('.cat .cimg').length > 6);
await p.waitForTimeout(2500);
await shot('real-categories');
const tiles = await p.locator('.cat').evaluateAll((l) => l.slice(0, 12).map((c) => `${c.querySelector('b').textContent}:${c.querySelectorAll('.cimg').length}`));
console.log('      tiles:', tiles.join(' '));
ok('Category tiles show real artwork');
await p.locator('.cat[data-cat="upcoming"]').click();
await until(() => document.querySelector('.chero h1')?.textContent === 'Upcoming' && document.querySelector('.row .card'));
await p.waitForTimeout(1500);
await shot('real-upcoming');
const years = await p.locator('.row .card').first().getAttribute('aria-label');
console.log('      upcoming:', years);
ok('Upcoming opens');
await p.evaluate(() => document.querySelector('[data-go="search"]').click());
await until(() => document.querySelector('.kb'));
for (const c of 'matrix') await p.locator(`.kb [data-k="${c}"]`).click();
await until(() => document.querySelector('#res .card'));
await p.waitForTimeout(1200);
await shot('real-search');
const found = await p.locator('#res .card').evaluateAll((l) => l.slice(0, 4).map((c) => c.getAttribute('aria-label')));
console.log('      search:', found.join(', '));
assert.ok(found.some((n) => /matrix/i.test(n)));
ok('Search finds real titles');
console.log('      hosts:', [...hosts].join(', '));
console.log('      failed requests:', [...bad].slice(0, 12).join(' ; ') || 'none');
assert.deepEqual(errors, []);
ok('No page errors');
await b.close();
console.log('Real services: passed');
